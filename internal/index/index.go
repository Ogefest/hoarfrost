// Schema is the PostgreSQL schema holding the index in production.
const Schema = "archive_index"

// schemaVersion identifies the layout of the index. The index is derived
// data, so a schema with another version is dropped and rebuilt from
// storage rather than migrated. Bump it on every schema change.
const schemaVersion = 5

// epochStatsSelect computes epoch_stats rows from records; saved is the size
// of the original records that revisits stand for.
const epochStatsSelect = `SELECT r.storage AS storage, r.epoch AS epoch, count(*) AS records,
	count(*) FILTER (WHERE r.type = 'revisit') AS revisits, coalesce(sum(o.length),0) AS saved
	FROM records r LEFT JOIN records o ON r.type = 'revisit' AND o.record_id = r.refers_to`

// Long strings (URLs, SURT keys) are looked up through small hashes instead
// of B-tree indexes on the whole string: records.surt_hash (CRC-32 of the
// SURT key, rechecked against surt) and urls.uri_md5 (MD5 of the URL, unique).
//
// Every row derived from an epoch references epochs, so dropping an epoch
// row removes its records, pages, files and totals. Revisits do not
// reference their originals by a foreign key: a damaged archive must still
// be indexable, and verification reports dangling revisits.
const schema = `
CREATE TABLE index_meta (version INTEGER NOT NULL);

CREATE TABLE epochs (
  storage     TEXT NOT NULL,
  epoch       TEXT NOT NULL,
  state       TEXT NOT NULL DEFAULT 'open',
  wacz_key    TEXT,
  sha256      TEXT,
  size        BIGINT,
  sealed_at   TIMESTAMPTZ,
  verified_at TIMESTAMPTZ,
  error       TEXT,
  PRIMARY KEY (storage, epoch)
);

CREATE TABLE files (
  storage  TEXT NOT NULL,
  location TEXT NOT NULL,
  epoch    TEXT NOT NULL,
  size     BIGINT NOT NULL,
  PRIMARY KEY (storage, location),
  FOREIGN KEY (storage, epoch) REFERENCES epochs ON DELETE CASCADE
);
CREATE INDEX files_epoch ON files(storage, epoch);

CREATE TABLE records (
  record_id TEXT PRIMARY KEY,
  storage   TEXT NOT NULL,
  epoch     TEXT NOT NULL,
  uri       TEXT NOT NULL,
  surt      TEXT NOT NULL,
  surt_hash INTEGER NOT NULL, -- CRC-32 (IEEE) of surt
  date      TIMESTAMPTZ NOT NULL,
  type      TEXT NOT NULL,
  mime      TEXT,
  status    INTEGER,
  digest    TEXT,
  refers_to TEXT,
  location  TEXT NOT NULL,
  "offset"  BIGINT NOT NULL,
  length    BIGINT NOT NULL,
  file      TEXT NOT NULL,
  FOREIGN KEY (storage, epoch) REFERENCES epochs ON DELETE CASCADE
);
CREATE INDEX rec_digest ON records(storage, epoch, digest);
CREATE INDEX rec_surt ON records(surt_hash, date);
CREATE INDEX rec_epoch ON records(storage, epoch, file);

-- One row per URL and storage: seen in a feed or sitemap, and described by
-- its latest capture (title, description, schema.org data).
CREATE TABLE urls (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  storage       TEXT NOT NULL,
  uri           TEXT NOT NULL,
  uri_md5       UUID NOT NULL,
  first_seen    TIMESTAMPTZ NOT NULL,
  last_captured TIMESTAMPTZ,
  title         TEXT,
  description   TEXT,
  published     TIMESTAMPTZ,
  authors       TEXT[],
  schema_types  TEXT[],
  schema_org    JSONB,
  UNIQUE (storage, uri_md5)
);

CREATE TABLE pages (
  page_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  metadata_id  TEXT NOT NULL UNIQUE,
  record_id    TEXT REFERENCES records ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  url_id       BIGINT NOT NULL REFERENCES urls,
  storage      TEXT NOT NULL,
  epoch        TEXT NOT NULL,
  uri          TEXT NOT NULL,
  title        TEXT,
  description  TEXT,
  captured     TIMESTAMPTZ NOT NULL,
  published    TIMESTAMPTZ,
  authors      TEXT[],
  schema_types TEXT[],
  schema_org   JSONB,
  source       TEXT,
  engine       TEXT,
  kind         TEXT,
  mime         TEXT,
  status       INTEGER,
  fallback     BOOLEAN NOT NULL DEFAULT false,
  text_len     INTEGER NOT NULL DEFAULT 0,
  resources    INTEGER NOT NULL DEFAULT 0,
  file         TEXT NOT NULL,
  location     TEXT NOT NULL,
  "offset"     BIGINT NOT NULL,
  length       BIGINT NOT NULL,
  search       TSVECTOR NOT NULL, -- folded title (A), description (B) and text (C)
  FOREIGN KEY (storage, epoch) REFERENCES epochs ON DELETE CASCADE
);
CREATE INDEX pages_url ON pages(url_id, captured);
CREATE INDEX pages_record ON pages(record_id);
CREATE INDEX pages_epoch ON pages(storage, epoch);
CREATE INDEX pages_captured ON pages(captured);
CREATE INDEX pages_source ON pages(source, captured);
CREATE INDEX pages_search ON pages USING GIN (search);

-- Per-epoch totals kept up to date on every insert, so the dashboard does
-- not scan the records table.
CREATE TABLE epoch_stats (
  storage  TEXT NOT NULL,
  epoch    TEXT NOT NULL,
  records  BIGINT NOT NULL,
  revisits BIGINT NOT NULL,
  saved    BIGINT NOT NULL,
  PRIMARY KEY (storage, epoch),
  FOREIGN KEY (storage, epoch) REFERENCES epochs ON DELETE CASCADE
);
`

// Epoch states.
