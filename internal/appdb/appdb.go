// Package appdb opens the application schema of the database, the
// operational state of an instance: users, sessions, API tokens, the job
// queue and the capture configuration (sources and their poll state). It is
// backed up but is not part of the archive.
package appdb

import (
	"context"
	"database/sql"

	"github.com/ogefest/hoarfrost/internal/pgdb"
)

// Schema is the PostgreSQL schema holding the application tables.
const Schema = "app"

var migrations = []string{`
CREATE TABLE users (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login   TEXT NOT NULL UNIQUE,
  pwhash  TEXT NOT NULL,
  role    TEXT NOT NULL,
  created TEXT NOT NULL
);
CREATE TABLE sessions (
  id      TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires TEXT NOT NULL,
  csrf    TEXT NOT NULL
);
CREATE TABLE api_tokens (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  name       TEXT NOT NULL,
  created    TEXT NOT NULL,
  last_used  TEXT
);
CREATE TABLE jobs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url         TEXT NOT NULL,
  domain      TEXT NOT NULL,
  source      TEXT NOT NULL,
  storage     TEXT NOT NULL DEFAULT 'default',
  engine      TEXT NOT NULL,
  priority    INTEGER NOT NULL DEFAULT 100,
  fallback    BOOLEAN NOT NULL DEFAULT false,
  state       TEXT NOT NULL DEFAULT 'queued',
  worker      TEXT,
  epoch       TEXT,
  lease_until BIGINT,
  not_before  BIGINT NOT NULL DEFAULT 0,
  attempts    INTEGER NOT NULL DEFAULT 0,
  last_error  TEXT,
  capture     TEXT,
  created     BIGINT NOT NULL,
  finished    BIGINT
);
CREATE INDEX jobs_pick ON jobs(state, priority, created);
CREATE INDEX jobs_domain ON jobs(domain, state);
CREATE INDEX jobs_epoch ON jobs(epoch, state);
CREATE INDEX jobs_url ON jobs(url) WHERE state IN ('queued', 'leased');
CREATE TABLE sources (
  name       TEXT PRIMARY KEY,
  config     TEXT NOT NULL, -- JSON of config.Source
  created    BIGINT NOT NULL,
  updated    BIGINT NOT NULL,
  last_poll  BIGINT,
  found      INTEGER NOT NULL DEFAULT 0,
  new        INTEGER NOT NULL DEFAULT 0,
  last_error TEXT
);
CREATE TABLE settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL -- JSON
);
`, `
-- Times as timestamptz instead of RFC 3339 text and Unix numbers.
ALTER TABLE users ALTER created TYPE TIMESTAMPTZ USING created::timestamptz,
  ALTER created SET DEFAULT now();
ALTER TABLE sessions ALTER expires TYPE TIMESTAMPTZ USING expires::timestamptz;
ALTER TABLE api_tokens ALTER created TYPE TIMESTAMPTZ USING created::timestamptz,
  ALTER created SET DEFAULT now(),
  ALTER last_used TYPE TIMESTAMPTZ USING nullif(last_used, '')::timestamptz;
ALTER TABLE jobs ALTER lease_until TYPE TIMESTAMPTZ USING to_timestamp(lease_until / 1000.0),
  ALTER not_before DROP DEFAULT, ALTER not_before DROP NOT NULL,
  ALTER not_before TYPE TIMESTAMPTZ USING CASE WHEN not_before > 0 THEN to_timestamp(not_before / 1000.0) END,
  ALTER created TYPE TIMESTAMPTZ USING to_timestamp(created), ALTER created SET DEFAULT now(),
  ALTER finished TYPE TIMESTAMPTZ USING to_timestamp(finished);
ALTER TABLE sources ALTER created TYPE TIMESTAMPTZ USING to_timestamp(created / 1000.0),
  ALTER updated TYPE TIMESTAMPTZ USING to_timestamp(updated / 1000.0),
  ALTER last_poll TYPE TIMESTAMPTZ USING to_timestamp(last_poll / 1000.0);
`, `
-- Read-only API keys for applications, independent of user accounts.
CREATE TABLE api_keys (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_hash   TEXT NOT NULL UNIQUE,
  name       TEXT NOT NULL,
  created    TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by TEXT NOT NULL,
  expires    TIMESTAMPTZ,
  last_used  TIMESTAMPTZ
);
`, `
-- Time of the last poll without errors, for alerting on failing sources.
ALTER TABLE sources ADD COLUMN last_success TIMESTAMPTZ;
UPDATE sources SET last_success = last_poll WHERE last_error IS NULL;
`, `
-- Origins of discovered URLs and the origin their site lives on, learned
-- from a permanent redirect of the whole host (example.com -> www.example.com).
CREATE TABLE host_aliases (
  origin  TEXT PRIMARY KEY,
  target  TEXT NOT NULL,
  checked TIMESTAMPTZ NOT NULL
);
`}

// Open connects to the database at url, uses schema (Schema in production)
// and applies migrations.
func Open(ctx context.Context, url, schema string) (*sql.DB, error) {
	db, err := pgdb.Open(ctx, url, schema)
	if err != nil {
		return nil, err
	}
	if err := pgdb.Migrate(ctx, db, migrations); err != nil {
		db.Close()
		return nil, err
	}
	return db, nil
}
